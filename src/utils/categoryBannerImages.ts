/** Returns the first banner image for a given category, or null if not found */
export function getCategoryBanner(category: string): string | null {
  const images = CATEGORY_BANNERS[category];
  return images ? images[0] : null;
}

/** Returns all banner options for a given category + a few generic ones */
export function getCategoryBannerOptions(category: string): string[] {
  const categoryImages = CATEGORY_BANNERS[category] || [];
  const generic = [
    'https://images.unsplash.com/photo-1497366216548-37526070297c?w=800&h=400&fit=crop',
    'https://images.unsplash.com/photo-1521737604893-d14cc237f11d?w=800&h=400&fit=crop',
    'https://images.unsplash.com/photo-1552664730-d307ca884978?w=800&h=400&fit=crop',
    'https://images.unsplash.com/photo-1522202176988-66273c2fd55f?w=800&h=400&fit=crop',
    'https://images.unsplash.com/photo-1542744094-24638eff58bb?w=800&h=400&fit=crop',
  ];
  // Combine category-specific first, then generic (deduped)
  const all = [...categoryImages, ...generic];
  return [...new Set(all)];
}
